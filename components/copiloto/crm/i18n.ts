const I18N_EN_SORTED = [...I18N_PAIRS].sort((a, b) => b[1].length - a[1].length)
const I18N_EXACT_EN = new Map(I18N_PAIRS.map(([es, en]) => [en, es] as [string, string]))

/** Traducción exacta de un literal de interfaz (los componentes
 *  escriben en inglés; en modo 'en' el texto pasa intacto). */
export function tx(s: string): string {
  if (typeof s !== "string") return s
  return LANG === "es" ? (I18N_EXACT_EN.get(s) ?? s) : s
}

let txCache: { re: RegExp; map: Map<string, string> } | null = null
/** Traducción de textos dinámicos (con nombres/cifras dentro): una sola
 *  pasada con límites de palabra, como en el prototipo — un patrón solo
 *  se traduce si no está pegado a otra letra, y el texto ya traducido
 *  nunca se re-escanea. Solo actúa en modo 'es'. */
export function txText(s: string): string {
  if (typeof s !== "string" || !s || LANG !== "es") return s
  if (!txCache) {
    const map = new Map<string, string>()
    for (const [es, en] of I18N_EN_SORTED) { if (en && !map.has(en)) map.set(en, es) }
    const LET = "[A-Za-z\u00C0-\u00FF]"
    const pats = [...map.keys()].filter((k) => new RegExp(LET).test(k))
    const esc = (x: string) => x.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    const alt = pats.map((k) => {
      const pre = new RegExp("^" + LET).test(k) ? "(?<!" + LET + ")" : ""
      const post = new RegExp(LET + "$").test(k) ? "(?!" + LET + ")" : ""
      return "(?:" + pre + esc(k) + post + ")"
    }).join("|")
    txCache = { re: new RegExp("(" + alt + ")", "g"), map }
  }
  return s.replace(txCache.re, (m) => txCache!.map.get(m) ?? m)
}
